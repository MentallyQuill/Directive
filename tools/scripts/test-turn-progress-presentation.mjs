import assert from 'node:assert/strict';
import * as activity from '../../src/hosts/sillytavern/turn-activity-indicator.js';
import * as bridge from '../../src/hosts/sillytavern/runtime-bridge.mjs';
import { __directiveEventTestHooks as events } from '../../src/hosts/sillytavern/shell-events.js';
import { createSillyTavernGenerationClient } from '../../src/hosts/sillytavern/generation-client.mjs';

assert.equal(typeof activity.recordDirectiveTurnProgress, 'function', 'real runtime operations must reach the activity presentation');
const snapshot = () => activity.__directiveTurnActivityTestHooks.progress();
const start = (operationId, stage) => ({ type: 'start', operationId, stage, startedAt: performance.now() });
const finish = (operationId, outcome = 'complete') => ({ type: 'finish', operationId, outcome, endedAt: performance.now() });
activity.disposeDirectiveTurnActivity();
const token = activity.markDirectiveTurnActivity({ hostGeneration: true });
activity.recordDirectiveTurnProgress(start('a', 'reviewing-events'));
assert.equal(snapshot().presentation.title, 'Reviewing recent events...');
activity.recordDirectiveTurnProgress(start('b', 'updating-characters'));
assert.equal(snapshot().active.length, 2, 'overlapping operations are retained');
activity.recordDirectiveTurnProgress(finish('b', 'failed'));
assert.equal(snapshot().presentation.title, 'Reviewing recent events...', 'finishing newer work restores still-active work');
assert.equal(snapshot().history.find(item => item.operationId === 'b').outcome, 'failed');
activity.recordDirectiveTurnProgress({ type: 'update', operationId: 'a', attempt: 2, text: 'PRIVATE RESPONSE', prompt: 'SECRET' });
assert.equal(snapshot().presentation.title, 'Reviewing recent events... (attempt 2)');
assert.doesNotMatch(JSON.stringify(snapshot()), /PRIVATE|SECRET/);
activity.recordDirectiveTurnProgress(start('unknown', 'reading-minds'));
assert.equal(snapshot().active.length, 1, 'unknown stages never become reassuring copy');
activity.recordDirectiveTurnProgress(finish('a'));
activity.resolveDirectiveHostGenerationHandoff({ token });
assert.equal(snapshot().presentation.title, 'Waiting for the reply...');
const historyBefore = snapshot().history.length;
await new Promise(resolve => setTimeout(resolve, 1050));
assert.equal(snapshot().history.length, historyBefore, 'time cannot invent a stage');
assert.equal(snapshot().presentation.title, 'Waiting for the reply...');

let completeBackground;
const client = createSillyTavernGenerationClient({ contextFactory: () => ({ generateRaw: () => new Promise(resolve => { completeBackground = resolve; }) }) });
const background = client.generate('episodeEvaluator', {});
events.handleStreamTokenReceived('private background chunk');
events.handleGenerationEnded();
assert.equal(snapshot().presentation.title, 'Waiting for the reply...', 'owned background streams/end cannot relabel or end the reply');
completeBackground({text: 'ok'});
await background;
events.handleStreamTokenReceived('');
assert.equal(snapshot().presentation.title, 'Waiting for the reply...', 'empty chunks do not prove response text');
events.handleStreamTokenReceived('reply text');
assert.equal(snapshot().presentation.title, 'Receiving the reply...');
assert.doesNotMatch(JSON.stringify(snapshot()), /reply text/);
events.handleGenerationEnded();
assert.equal(snapshot().presentation, null);
activity.recordDirectiveTurnProgress(finish('a'));
assert.equal(snapshot().presentation, null, 'late completion never resurrects the card');

activity.recordDirectiveTurnProgress(start('post-reply', 'reviewing-episode'));
assert.equal(snapshot().presentation.title, 'Reviewing the episode...', 'real post-reply analysis is visible without a waiting placeholder');
activity.recordDirectiveTurnProgress(finish('post-reply'));
assert.equal(snapshot().presentation, null, 'post-reply operation owns and clears its own card');
activity.recordDirectiveTurnProgress(start('idle-save', 'saving'));
assert.equal(snapshot().presentation, null, 'unrelated idle saves do not create turn notifications');
activity.recordDirectiveTurnProgress(finish('idle-save'));
const main = activity.markDirectiveTurnActivity({hostGeneration: true});
activity.resolveDirectiveHostGenerationHandoff({token: main});
activity.recordDirectiveTurnProgress(start('overlap', 'reviewing-episode'));
activity.finishDirectiveHostGenerationActivities();
assert.equal(snapshot().presentation.title, 'Reviewing the episode...', 'host end preserves actual background work');
activity.recordDirectiveTurnProgress(finish('overlap'));
assert.equal(snapshot().presentation, null);

let releaseDirect;
const directClient = createSillyTavernGenerationClient({providerClient: {generate: () => new Promise(resolve => {releaseDirect = resolve;})}});
const directRequest = directClient.generate('episodeEvaluator', {});
const directOverlap = activity.markDirectiveTurnActivity({hostGeneration: true});
activity.resolveDirectiveHostGenerationHandoff({token: directOverlap});
events.handleStreamTokenReceived('main reply alongside direct request');
assert.equal(snapshot().presentation.title, 'Receiving the reply...', 'direct provider work does not own host stream events');
events.handleGenerationEnded();
assert.equal(snapshot().presentation, null, 'direct provider work does not mask the main host end');
releaseDirect({text: 'ok'});
await directRequest;

let listener;
let unsubscribed = 0;
let resets = 0;
bridge.setSillyTavernDirectiveRuntimeBridge({app: {resetTurnProgress() {resets++;}, subscribeTurnProgress(callback) {listener = callback; return () => {unsubscribed++;};}}});
activity.markDirectiveTurnActivity();
listener(start('bridge', 'saving'));
assert.equal(snapshot().presentation.title, 'Saving story progress...');
events.disposeSillyTavernDirectiveEventLifecycle();
assert.equal(resets, 1, 'lifecycle disposal invalidates pending runtime scopes before they can publish later stages');
bridge.setSillyTavernDirectiveRuntimeBridge({app: null});
assert.equal(unsubscribed, 1, 'bridge replacement unsubscribes old runtime');
assert.equal(snapshot().active.length, 0);
activity.cancelActiveDirectiveTurnActivities();
activity.recordDirectiveTurnProgress(finish('bridge'));
const newer = activity.markDirectiveTurnActivity();
assert.equal(snapshot().history.length, 0, 'new turn does not inherit canceled history');
activity.finishDirectiveTurnActivity(newer);
bridge.clearSillyTavernDirectiveRuntimeBridge();
console.log('PASS truthful turn progress presentation and host ownership');
