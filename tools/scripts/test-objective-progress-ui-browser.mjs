import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
const root=process.cwd();
const capture = async (page, name) => {
 if (process.env.DIRECTIVE_OBJECTIVE_SCREENSHOTS !== '1') return;
 await fs.mkdir(path.join(root,'artifacts/objective-progress'),{recursive:true});
 await page.screenshot({path:path.join(root,`artifacts/objective-progress/${name}.png`),fullPage:true});
};
const server=http.createServer(async(req,res)=>{try{const url=new URL(req.url,'http://localhost');if(url.pathname==='/'){res.setHeader('Content-Type','text/html');res.end('<link rel="stylesheet" href="/styles/directive.css"><button id="opener">Open</button><main id="cards"></main>');return;}const file=path.resolve(root,'.'+url.pathname);if(!file.startsWith(root+path.sep)){res.writeHead(403).end();return;}res.setHeader('Content-Type',file.endsWith('.css')?'text/css':'text/javascript');res.end(await fs.readFile(file));}catch{res.writeHead(404).end();}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 await page.goto(`http://127.0.0.1:${server.address().port}`);
 await page.evaluate(async()=>{
  const {registerRuntimeAction}=await import('/src/runtime/runtime-actions.js');
  window.shellEscapes=0; document.addEventListener('keydown',event=>{if(event.key==='Escape')window.shellEscapes++;});
  window.calls=[];registerRuntimeAction('runtime.adjustObjectiveProgress',payload=>{window.calls.push(payload);return new Promise(resolve=>window.settle=resolve);});
  window.controls=await import('/src/ui/objective-progress-controls.js');
  window.objective={id:'objective-x',title:'Secure passage',status:'terminal',progressControl:{mode:'automatic',expectedRevision:2,allowedResolutions:[{disposition:'handedOff',label:'Handed over'}]}};
  document.querySelector('#opener').onclick=()=>window.controls.showObjectiveProgressDialog({objective:window.objective,mission:{id:'mission-x',runId:'run-x'},onCommitted:()=>window.committed=true});
 });
 await page.locator('#opener').click();
 await page.evaluate(()=>{document.body.style.transform='translateZ(0)';document.body.style.height='0px';});
 assert.ok(await page.evaluate(()=>{const r=document.querySelector('.objective-progress-dialog').getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;}),'dialog must stay in viewport when host body forms a zero-height fixed containing block');
 await page.evaluate(()=>{document.body.style.transform='';document.body.style.height='';});
 await page.getByRole('button',{name:'Still underway',exact:true}).click();
 assert.equal(await page.getByRole('status').textContent(),'Saving progress…');
 await page.keyboard.press('Escape');
 assert.equal(await page.evaluate(()=>window.shellEscapes),0,'pending dialog Escape must not close the runtime shell');
 await page.getByRole('dialog').waitFor();
 assert.equal(await page.evaluate(()=>window.committed),undefined);
 assert.deepEqual(await page.evaluate(()=>window.calls[0]),{missionId:'mission-x',objectiveId:'objective-x',expectedRunId:'run-x',expectedRevision:2,action:'reopen'});
 await page.evaluate(()=>window.settle({ok:false,message:'Progress changed. Review the current objective and try again.'}));
 await page.getByText('Progress changed. Review the current objective and try again.').waitFor();
 await page.getByRole('button',{name:'Handed over',exact:true}).click();
 await page.evaluate(()=>window.settle({ok:true,status:'committed'}));
 await page.getByRole('dialog').waitFor({state:'detached'});
 assert.equal(await page.evaluate(()=>document.activeElement.id),'opener');
 assert.equal(await page.evaluate(()=>window.committed),true);
 await page.locator('#opener').click();
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.evaluate(()=>document.activeElement.textContent),'Cancel');
 await page.keyboard.press('Escape');
 assert.equal(await page.evaluate(()=>document.activeElement.id),'opener');
 assert.equal(await page.evaluate(()=>window.shellEscapes),0,'dialog Escape must not reach the runtime shell');
 await page.evaluate(()=>{window.objective.progressControl={...window.objective.progressControl,mode:'confirmation_required',proposal:{id:'proposal-x',disposition:'handedOff',label:'Handed over'}};window.controls.appendObjectiveProgressControls(document.querySelector('#cards'),{objective:window.objective,mission:{id:'mission-x',runId:'run-x'},onCommitted:()=>{}});});
 await page.getByText('Completion needs your confirmation.').waitFor();
 await page.getByRole('button',{name:'Confirm Handed over'}).click();
 assert.equal(await page.evaluate(()=>window.calls.at(-1).action),'acceptProposal');
 assert.equal(await page.evaluate(()=>window.calls.at(-1).proposalId),'proposal-x');
 await page.evaluate(()=>window.settle({ok:true,status:'committed'}));
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile should not overflow');
 await page.evaluate(async()=>{window.notices=await import('/src/ui/gameplay-notification-center.js');window.notices.publishGameplayNotifications([{id:'notice-x',route:'mission',subjectId:'mission-x',title:'Objective complete',progressAction:{missionId:'mission-x',objectiveId:'objective-x',expectedRunId:'run-x',expectedRevision:2,action:'reopen'}}]);});
 await page.getByRole('button',{name:'Still underway',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.calls.at(-1).action),'reopen');
 await page.evaluate(()=>window.settle({ok:false,message:'Could not save. Try again.'}));
 await page.getByText('Could not save. Try again.').waitFor();
 await page.evaluate(()=>window.notices.handleGameplayNotificationUiMessage({type:'directive.gameplayNotifications.retire.v1',payload:{ids:['notice-x']}}));
 await page.locator('[data-notification-id="notice-x"]').waitFor({state:'detached'});
 await page.evaluate(()=>{window.notices.publishGameplayNotifications([{id:'grouped-x',route:'mission',subjectId:'mission-x',title:'Objectives complete',objectiveIds:['objective-x','objective-y'],reviewObjectives:true}]);});
 await page.getByRole('button',{name:'Review objectives'}).waitFor();
 await page.evaluate(()=>window.notices.handleGameplayNotificationUiMessage({type:'directive.gameplayNotifications.retire.v1',payload:{missionId:'mission-x',objectiveIds:['objective-x']}}));
 await page.locator('[data-notification-id="grouped-x"]').waitFor({state:'detached',timeout:1000});
 await page.evaluate(async()=>{
   document.querySelector('#cards').replaceChildren();
   document.querySelector('#cards').className='directive-expanded-shell';
   const {renderMissionPanel}=await import('/src/ui/mission-panel.js');
   const projection={kind:'directive.playerProjection.v1',time:{kind:'directive.timePlayerProjection.v1'},player:{kind:'directive.playerIdentityProjection.v1'},people:{kind:'directive.peoplePlayerProjection.v1'},ship:{kind:'directive.shipPlayerProjection.v1'},commandBearing:{kind:'directive.commandBearingPlayerProjection.v1'},mission:{kind:'directive.missionPlayerProjection.v1',missionId:'mission-x',runId:'run-x',title:'A different mission',status:'active',summary:'Arrange safe passage.',objectives:[{...window.objective,class:'required',progressControl:{...window.objective.progressControl,mode:'player_set',proposal:null}}]}};
   renderMissionPanel(document.querySelector('#cards'),{v1PlayerProjection:projection});
 });
 await page.locator('.mission-mobile-detail').getByRole('button',{name:'Adjust progress',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 assert.ok(await page.evaluate(()=>document.querySelector('.objective-progress-dialog').getBoundingClientRect().right<=innerWidth));
 await capture(page,'mobile-dialog');
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:1280,height:900});
 await page.locator('.mission-desktop-detail').getByRole('button',{name:'Adjust progress',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await capture(page,'desktop-dialog');
 await page.keyboard.press('Escape');
 console.log('Objective progress controlled browser checks passed');
} finally {await browser.close();await new Promise(r=>server.close(r));}
