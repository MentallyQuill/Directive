import assert from 'node:assert/strict';
import {createTurnCommit} from '../../src/runtime/turn-state-reconciler.mjs';
import {createStateDeltaGateway} from '../../src/runtime/state-delta-gateway.mjs';
import {createAshesInitialState} from './v1-test-fixtures.mjs';
let state = createAshesInitialState({campaignId:'campaign.one',saveId:'save.one',chatId:'chat.one'});
const before = structuredClone(state); const after = structuredClone(state);
after.campaign.title = 'A reconciled turn'; after.mission.v1.revision++;
let saves = 0; let fail = true;
const gateway = createStateDeltaGateway({getState:()=>state,setState:next=>{state=next;},persist:async()=>{saves++; if(fail) throw new Error('disk unavailable');}});
const proposal = createTurnCommit({before,after,turnKey:'turn.test'});
assert.equal(saves,0); assert.deepEqual(state,before);
await assert.rejects(()=>gateway.applyProposal(proposal)); assert.deepEqual(state,before);
fail = false; await gateway.applyProposal(proposal);
assert.equal(saves,2); assert.equal(state.campaign.title,after.campaign.title);
assert.equal(state.mission.v1.revision,after.mission.v1.revision);
assert.equal(state.stateCustody.revision,before.stateCustody.revision+1);
await gateway.applyProposal(proposal); assert.equal(saves,2);
assert.throws(()=>createTurnCommit({before,after:{...after,settings:{}},turnKey:'bad'}),/forbidden-root/);
assert.throws(()=>createTurnCommit({before,after:{...after,stateCustody:{revision:5}},turnKey:'bad'}),/forbidden-root/);
assert.equal(createTurnCommit({before,after:structuredClone(before),turnKey:'empty'}),null);
assert.throws(()=>createTurnCommit({before:{},after:{settings:null},turnKey:'bad'}),/forbidden-root/);
assert.throws(()=>createTurnCommit({before:{campaign:null},after:{},turnKey:'bad'}),/root-removal/);
console.log('Turn state reconciliation tests passed.');
