import assert from 'node:assert/strict';
import { createFakeDirectiveHost, createFakeGenerationClient } from '../../src/hosts/fake/fake-host.mjs';
import { createDirectiveRuntimeApp } from '../../src/runtime/runtime-app.mjs';
import { loadAshesRuntimeAssets } from './v1-test-fixtures.mjs';
let preferences={pov:'second-person',tense:'present'};
const host=createFakeDirectiveHost({chatNative:true,generation:createFakeGenerationClient({responses:{openingSceneDirector:{text:JSON.stringify({kind:'directive.openingDirection.v1',sceneMaterialIds:['scene:0'],backgroundIds:['background:briefBiography'],emphasis:'balanced'})},narration:{text:'The door ahead of you is closed.'}}})});
host.narration={getSettings:()=>preferences,updateSettings:p=>(preferences={...preferences,...p})};
let sequence=0;
const app=createDirectiveRuntimeApp({host,packageLoader:async()=>loadAshesRuntimeAssets(),idFactory:p=>`${p}.${++sequence}`,now:()=> '2026-09-08T04:00:00.000Z'});
await app.initialize();
assert.equal(typeof app.updateNarrationSettings,'function');
await app.startCreatorDraft();
await app.saveCreatorDraft({patch:{activeStep:'review',input:{identity:{name:'Opening Tester',pronounsOrAddress:'they/them',speciesId:'human',ageBandId:'mid-career',appearance:'Attentive.'},service:{careerBackgroundId:'tactical-security',formativeExperienceId:'dominion-war-fleet-service',assignmentReasonId:'experienced-outsider-transfer'},personality:{traits:{insight:'perceptive',connection:'candid',execution:'decisive'},flawId:'impatient'},dossier:{briefBiography:'A command officer who coordinated refugee transports.',publicReputation:'An attentive command officer.'}}}});
await app.handleHostGenerationStopped();
const started=await app.acceptCreatorDraftAndStartCampaign();
assert.equal(started.opening.ok,true,JSON.stringify(started.opening));
assert.equal(host.chat.messages()[0].text,'The door ahead of you is closed.');
assert.equal(host.generation.calls().filter(c=>c.role==='openingSceneDirector').length,1);
assert.match(JSON.stringify(host.generation.calls()),/refugee transports/);
await app.updateNarrationSettings({pov:'third-person-limited',tense:'past'});
const view=await app.getCurrentView();assert.equal(view.narrationSettings.tense,'past');
assert.match(JSON.stringify(host.prompt.inspect()),/Write in past tense/);
assert.match(JSON.stringify(host.prompt.inspect()),/openingDirection/);
assert.doesNotMatch(JSON.stringify(host.prompt.inspect()),/canonicalOpeningMessage/);
const reloaded=createDirectiveRuntimeApp({host,packageLoader:async()=>loadAshesRuntimeAssets()});await reloaded.initialize();await reloaded.openCampaignChat();
assert.equal(host.chat.messages().length,1);
assert.equal(host.generation.calls().filter(c=>c.role==='openingSceneDirector').length,1);
console.log('Opening runtime and global narration settings passed.');
const diagnostics=JSON.parse((await app.exportSupportDiagnostics()).jsonText);
assert.deepEqual(diagnostics.narrationSettings,{pov:'third-person-limited',tense:'past'});
assert.deepEqual(diagnostics.openingNarrationSettings,{pov:'second-person',tense:'present'});
assert(!diagnostics.openingInputs,'metadata-only support must not export the character background');
