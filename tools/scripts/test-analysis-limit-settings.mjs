import assert from 'node:assert/strict';
import { DEFAULT_ANALYSIS_LIMITS, ANALYSIS_LIMIT_DESCRIPTORS, MAX_TIMER_TIMEOUT_SECONDS, normalizeAnalysisLimits } from '../../src/generation/analysis-limits.mjs';
import { createSillyTavernProviderSettingsStore, normalizeDirectiveProviderSettings } from '../../src/providers/directive-provider-settings.mjs';

assert.deepEqual(normalizeAnalysisLimits(), DEFAULT_ANALYSIS_LIMITS);
assert.equal(ANALYSIS_LIMIT_DESCRIPTORS.length, Object.keys(DEFAULT_ANALYSIS_LIMITS).length);
const normalized = normalizeAnalysisLimits({ threadMaxRecords: 80, continuityFactCharacters: 4096, threadInactivityRevisions: 0, continuityEvidenceQuoteCharacters: 3, requestContextCharacters: Infinity, unknown: 123 });
assert.equal(normalized.threadMaxRecords, 80);
assert.equal(normalized.continuityFactCharacters, 4096);
assert.equal(normalized.threadInactivityRevisions, 0);
assert.equal(normalized.continuityEvidenceQuoteCharacters, 12);
assert.equal(normalized.requestContextCharacters, 48000);
assert.equal(Object.hasOwn(normalized, 'unknown'), false);
const context = { extensionSettings: {}, saveSettingsDebounced() {} };
const store = createSillyTavernProviderSettingsStore({ context });
assert.equal(store.get('reasoning').roleLimits.storyDirectionAnalyst.maxTokens, null);
store.update('reasoning', { maxTokens: 262144, timeoutSeconds: 172800, roleLimits: { storyDirectionAnalyst: { maxTokens: 90000, maxAttempts: 5 } } });
store.update('reasoning', { roleLimits: { storyDirectionAnalyst: { timeoutSeconds: 3600 } } });
assert.deepEqual(store.get('reasoning').roleLimits.storyDirectionAnalyst, { maxTokens: 90000, timeoutSeconds: 3600, maxAttempts: 5 });
assert.equal(store.get('reasoning').maxTokens, 262144, 'old arbitrary output ceiling removed');
assert.equal(store.get('reasoning').timeoutSeconds, 172800, 'long requests respect browser timer range');
store.update('reasoning', { roleLimits: { storyDirectionAnalyst: { maxTokens: null } } });
assert.equal(store.get('reasoning').roleLimits.storyDirectionAnalyst.maxTokens, null, 'explicit inherit survives storage');
store.update('utility', { analysisLimits: { threadMaxRecords: 40 } });
store.update('utility', { analysisLimits: { continuityFactCharacters: 8192 } });
const reloaded = createSillyTavernProviderSettingsStore({ context });
assert.equal(reloaded.get('utility').analysisLimits.threadMaxRecords, 40);
assert.equal(reloaded.get('utility').analysisLimits.continuityFactCharacters, 8192);
assert.equal(reloaded.get('reasoning').roleLimits.storyDirectionAnalyst.timeoutSeconds, 3600);
assert.equal(normalizeDirectiveProviderSettings({ reasoning: { timeoutSeconds: Number.MAX_SAFE_INTEGER } }).reasoning.timeoutSeconds, MAX_TIMER_TIMEOUT_SECONDS);
assert.equal(Object.hasOwn(normalizeDirectiveProviderSettings({ utility: { roleLimits: { storyDirectionAnalyst: { maxTokens: 999 } } } }).utility.roleLimits, 'storyDirectionAnalyst'), false, 'role overrides belong to their registered lane');
console.log('Analysis limit settings tests passed.');
