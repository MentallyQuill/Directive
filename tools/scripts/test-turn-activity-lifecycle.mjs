import assert from 'node:assert/strict';
import * as activity from '../../src/hosts/sillytavern/turn-activity-indicator.js';
import * as bridge from '../../src/hosts/sillytavern/runtime-bridge.mjs';
import { __directiveEventTestHooks as events } from '../../src/hosts/sillytavern/shell-events.js';
import { registerRuntimeAction } from '../../src/runtime/runtime-actions.js';
registerRuntimeAction('runtime.refresh', () => ({ refreshed: true }));
const active = () => activity.__directiveTurnActivityTestHooks.activeActivities();
const result = { handled: true, abortDefaultGeneration: false, responseStrategy: 'injectAndContinue' };
const token = activity.markDirectiveTurnActivity();
activity.resolveDirectiveHostGenerationHandoff({ token });
await new Promise(resolve => setTimeout(resolve, 850));
assert.equal(active().length, 1, 'handoff remains owned beyond obsolete timer expiry');
assert.equal(active()[0].phase, 'waiting');
activity.disposeDirectiveTurnActivity();
const oldToken = activity.markDirectiveTurnActivity();
const currentToken = activity.markDirectiveTurnActivity();
assert.equal(activity.resolveDirectiveHostGenerationHandoff().ok, false, 'unowned handoff cannot affect any activity');
activity.finishDirectiveTurnActivity(oldToken);
assert.deepEqual(active().map(a => a.token), [currentToken], 'old operation completion preserves newer activity');
events.disposeSillyTavernDirectiveEventLifecycle();
assert.equal(active().length, 0, 'lifecycle disposal clears activity');
let resolve;
bridge.setSillyTavernDirectiveRuntimeBridge({turnOrchestrator: {interceptGeneration: () => new Promise(r => { resolve = r; })}});
const observation = activity.markDirectiveTurnActivity();
const pending = bridge.directiveGenerationInterceptor([], 8192, () => {}, 'normal');
resolve(result);
await pending;
assert.equal(active().find(a => a.token === observation).phase, 'reading', 'handoff cannot relabel other work');
assert.equal(active().filter(a => a.phase === 'waiting').length, 1, 'interceptor hands off its exact token');
events.handleGenerationEnded();
assert.deepEqual(active().map(a => a.token), [observation], 'end clears generation but preserves independent reading');
activity.disposeDirectiveTurnActivity();
const fast = bridge.directiveGenerationInterceptor([], 8192, () => {}, 'normal');
events.handleGenerationEnded();
resolve(result);
await fast;
assert.equal(active().length, 0, 'fast end cannot be resurrected by a late interceptor');
const switched = bridge.directiveGenerationInterceptor([], 8192, () => {}, 'normal');
const switchWork = events.handleChatChanged();
resolve(result);
await switched;
await switchWork;
assert.equal(active().length, 0, 'chat switch invalidates in-flight activity');
const disabled = bridge.directiveGenerationInterceptor([], 8192, () => {}, 'normal');
bridge.setSillyTavernDirectiveRuntimeEnabled(false);
resolve(result);
await disabled;
assert.equal(active().length, 0, 'disable invalidates in-flight activity');
// Stop removes its captured work before awaiting cancellation, leaving new work alone.
let releaseStop;
bridge.setSillyTavernDirectiveRuntimeBridge({ app: { handleHostGenerationStopped: () => new Promise(r => { releaseStop = r; }) } });
activity.markDirectiveTurnActivity();
const stopping = events.handleGenerationStopped();
assert.equal(active().length, 0, 'stop feedback clears immediately');
const newer = activity.markDirectiveTurnActivity();
releaseStop({ ok: true });
await stopping;
assert.deepEqual(active().map(a => a.token), [newer], 'old stop completion cannot clear newer work');
activity.disposeDirectiveTurnActivity();
bridge.setSillyTavernDirectiveRuntimeBridge({turnOrchestrator: { interceptGeneration() { throw new Error('test failure'); } }});
assert.equal((await bridge.directiveGenerationInterceptor([], 8192, () => {}, 'normal')).reason, 'interceptor-error');
assert.equal(active().length, 0, 'failed interception clears its own activity');
activity.markDirectiveTurnActivity();
bridge.setSillyTavernDirectiveRuntimeBridge({ active: false });
assert.equal(active().length, 0, 'disabled bridge replacement clears old work');
bridge.clearSillyTavernDirectiveRuntimeBridge();
console.log('PASS event-driven activity lifecycle');
