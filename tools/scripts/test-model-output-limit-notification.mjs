import assert from 'node:assert/strict';
import { installFakeDom } from './helpers/fake-dom.mjs';
import { handleModelOutputLimitUiMessage, modelOutputLimitMessage, resetModelOutputLimitNotification } from '../../src/ui/model-output-limit-notification.js';
import { showPresetUpdateNotification, resetPresetUpdateNotification } from '../../src/ui/preset-update-notification.js';
import { showSettlementRetryDialog, closeSettlementRetryDialog } from '../../src/ui/settlement-retry-dialog.js';
import { setDirectiveRuntimeApp } from '../../src/runtime/runtime-shell.js';
import { handleDirectiveUiMessage } from '../../src/hosts/sillytavern/bootstrap.js';

const document = installFakeDom();
const createElement = document.createElement.bind(document);
document.createElement = (...args) => { const element = createElement(...args); element.style.setProperty = (key, value) => { element.style[key] = value; }; return element; };
document.documentElement.style.setProperty = () => {};
globalThis.localStorage = { getItem: () => null, setItem() {} };
const message = (payload = {}) => ({ type: 'directive.modelOutputLimit.v1', payload });
const cards = () => document.documentElement.querySelectorAll('.directive-model-output-limit-notification');
const action = name => document.querySelector(`[data-model-output-limit-action="${name}"]`);
const copy = () => cards()[0].querySelector('.directive-gameplay-notification-summary').textContent;
assert.deepEqual(handleDirectiveUiMessage({ type: 'unrelated' }), { handled: false });
assert.equal(cards().length, 0);
assert.match(modelOutputLimitMessage(), /Try increasing Analysis Capacity/);
assert.match(modelOutputLimitMessage({ analysisCapacity: 5 }), /already at 5×/);
assert.match(modelOutputLimitMessage({ analysisCapacity: 5, hasOutputOverride: true }), /Increase or clear the exact output-token override/);
let opened = 0;
handleModelOutputLimitUiMessage(message(), { onOpenSettings: async () => { opened++; } });
handleModelOutputLimitUiMessage(message({ hasOutputOverride: true }));
handleModelOutputLimitUiMessage(message());
assert.equal(cards().length, 1);
assert.match(copy(), /does not change that override/, 'concurrent default failure must not erase outstanding override guidance');
const overrideDialog = showSettlementRetryDialog({ reasonCode: 'provider_token_limit' });
assert.match(overrideDialog.dialog.querySelector('.directive-settlement-retry-detail').textContent, /does not change that override/);
closeSettlementRetryDialog();
await action('dismiss').click();
assert.equal(cards().length, 0);
showPresetUpdateNotification();
handleModelOutputLimitUiMessage(message(), { onOpenSettings: async () => { opened++; } });
assert.match(copy(), /Try increasing Analysis Capacity/, 'dismiss clears prior override aggregation');
await action('open').click();
assert.equal(opened, 1);
assert.equal(cards().length, 0);
assert.equal(document.documentElement.querySelectorAll('.directive-preset-update-notification').length, 1, 'preset notice survives dismissing model limit');
handleModelOutputLimitUiMessage(message());
resetPresetUpdateNotification();
assert.equal(cards().length, 1, 'model notice survives dismissing preset notice');
resetModelOutputLimitNotification();
setDirectiveRuntimeApp({ getCurrentView: async () => ({ providerConfiguration: { settings: { utility: {}, reasoning: {} }, profiles: [], status: {} } }) });
const dialog = showSettlementRetryDialog({ reasonCode: 'provider_token_limit' });
assert.match(dialog.dialog.querySelector('.directive-settlement-retry-detail').textContent, /Analysis Capacity/);
handleDirectiveUiMessage(message());
await action('open').click();
assert.equal(dialog.overlay.isConnected, false, 'opening settings releases the blocking recovery modal');
assert.equal(document.activeElement?.dataset.settingsControl, 'analysis-capacity', 'navigation renders Settings and focuses the slider');
assert.equal(cards().length, 0);
console.log('Model output limit notification tests passed.');
