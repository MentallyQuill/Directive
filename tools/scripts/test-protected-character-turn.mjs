import assert from 'node:assert/strict';
import { prepareProtectedCharacterTurn } from '../../src/runtime/protected-character-turn.mjs';
import { createCharacterSceneAdmission } from '../../src/story/character-scene-admission.mjs';
import { captureV1StorySource } from '../../src/runtime/v1-accepted-pair-source.mjs';
import { createCharacterPublicationGuard } from '../../src/runtime/character-publication-guard.mjs';
const messages = [{ id: 'a1', mes: 'The bridge is quiet.', is_user: false, swipe_id: 0, swipes: ['The bridge is quiet.'] }, { id: 'u2', mes: 'I wait for a response.', is_user: true }];
const source = message => { const { role, ...value } = captureV1StorySource(message).value; return value; };
const sourcePair = { previousAssistant: source(messages[0]), currentPlayer: source(messages[1]) };
const admission = createCharacterSceneAdmission({ proposal: { participants: [], reactions: [], playerContext: [{ sourceSlot: 'currentPlayer', evidenceQuote: messages[1].mes }] }, sourcePair, playerId: 'person.player', knownPersonIds: new Set() });
const state = { player: { name: 'Tester' }, storySettlement: { branchId: 'save.test', revision: 1, activeEpisode: null, episodes: [], continuityEvents: [] } };
const before = structuredClone(state);
const identity = { bindingKey: 'chat.test', branchId: 'save.test', sourceDigest: 'a'.repeat(64), settingsDigest: 'b'.repeat(64), epoch: 1 };
let current = true, calls = 0;
const guard = createCharacterPublicationGuard({ publicationId: 'publication.turn', identity, baselineRows: messages, readRows: () => messages, readIdentity: () => current ? identity : null });
const generation = { async generate(role, request, options) {
  calls++; options.attemptBudget.claim(); const input = JSON.parse(request.messages[1].content);
  if (role === 'sceneNarrator') return { text: JSON.stringify({ segments: [{ kind: 'prose', id: 'segment.1', text: 'The quiet holds.' }] }) };
  assert.equal(role, 'characterKnowledgeReviewer');
  return { text: JSON.stringify({ kind: 'directive.characterKnowledgeReview.v1', candidateDigest: input.candidateDigest, supportDigest: input.supportDigest, verdict: 'pass', findings: [] }) };
} };
const turn = await prepareProtectedCharacterTurn({ generation, campaignState: state, crewDataset: {}, messages, sourcePair, admission, identity, guard, publicationId: 'publication.turn', expectedBinding: {}, sourceContributionIds: [] });
assert.equal(calls, 2);
assert.deepEqual(state, before);
let publicationAttempts = 0;
const publish = async options => { publicationAttempts++; assert.equal(options.text, 'The quiet holds.'); if (publicationAttempts === 1) throw Object.assign(new Error('pending'), { code: 'DIRECTIVE_CHARACTER_PUBLICATION_PENDING' }); return { ok: true, persisted: true }; };
await assert.rejects(turn.publish(publish), { code: 'DIRECTIVE_CHARACTER_PUBLICATION_PENDING' });
assert.equal((await turn.publish(publish)).persisted, true);
assert.equal(calls, 2, 'uncertain publication retry does not regenerate or review');
assert.equal(turn.attempts, 2);
assert.deepEqual(state, before);
console.log('PASS protected turn assembly, bounded physical calls and publication-only recovery');
